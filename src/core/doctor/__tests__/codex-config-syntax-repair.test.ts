test('doctor syntax repair preserves a concurrent content and mode edit after its snapshot', async (t) => {
  const root = await fixtureRoot(t);
  const codexHome = path.join(root, 'home-codex');
  await fs.mkdir(codexHome, { recursive: true });
  const file = await writeManagedProjectConfig(root, 'default_profile = "sks-fast-high"\n');
  const concurrent = `${MANAGED_MARKER}\nmodel = "user-concurrent-model"\n`;
  let injected = false;

  const report = await runCodexConfigSyntaxRepair({
    root,
    fix: true,
    codexHome,
    reportPath: null,
    writeCodexConfigGuardedImpl: async (input) => {
      if (!injected && input.configPath === file) {
        injected = true;
        await fs.writeFile(file, concurrent, { mode: 0o640 });
        await fs.chmod(file, 0o640);
      }
      return writeCodexConfigGuarded(input);
    }
  });

  assert.equal(report.ok, false);
  assert.ok(report.blockers.includes('project:config_write_refused:concurrent_change_detected'));
  assert.equal(await fs.readFile(file, 'utf8'), concurrent);
  assert.equal((await fs.stat(file)).mode & 0o777, 0o640);
});

test('doctor syntax repair refuses a symlinked config without touching its target', async (t) => {
  const root = await fixtureRoot(t);
  const codexHome = path.join(root, 'home-codex');
  const configPath = path.join(root, '.codex', 'config.toml');
  const external = path.join(root, 'external-user-config.toml');
  const source = `${MANAGED_MARKER}\ndefault_profile = "sks-fast-high"\n`;
  await fs.mkdir(path.dirname(configPath), { recursive: true });
  await fs.mkdir(codexHome, { recursive: true });
  await fs.writeFile(external, source, { mode: 0o640 });
  await fs.symlink(external, configPath);

  const report = await runCodexConfigSyntaxRepair({ root, fix: true, codexHome, reportPath: null });

  assert.equal(report.ok, false);
  assert.ok(report.blockers.some((item) => item.startsWith('project:config_snapshot_failed:')));
  assert.equal((await fs.lstat(configPath)).isSymbolicLink(), true);
  assert.equal(await fs.readlink(configPath), external);
  assert.equal(await fs.readFile(external, 'utf8'), source);
  assert.equal((await fs.stat(external)).mode & 0o777, 0o640);
});

test('doctor syntax repair refuses a symlinked project .codex ancestor without touching its target', async (t) => {
  const root = await fixtureRoot(t);
  const codexHome = path.join(root, 'home-codex');
  const externalCodex = path.join(root, 'external-codex');
  const source = `${MANAGED_MARKER}\ndefault_profile = "sks-fast-high"\n`;
  await fs.mkdir(externalCodex, { recursive: true });
  await fs.mkdir(codexHome, { recursive: true });
  await fs.writeFile(path.join(externalCodex, 'config.toml'), source, { mode: 0o640 });
  await fs.symlink(externalCodex, path.join(root, '.codex'));

  const report = await runCodexConfigSyntaxRepair({ root, fix: true, codexHome, reportPath: null });

  assert.equal(report.ok, false);
  assert.ok(report.blockers.includes(
    'project:config_parent_unsafe:project_codex_parent_symlink_refused'
  ));
  assert.equal((await fs.lstat(path.join(root, '.codex'))).isSymbolicLink(), true);
  assert.equal(await fs.readFile(path.join(externalCodex, 'config.toml'), 'utf8'), source);
  assert.equal((await fs.stat(path.join(externalCodex, 'config.toml'))).mode & 0o777, 0o640);
});
